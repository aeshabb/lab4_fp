(** {1 Let-binding операторы} *)

(** Функторный let-binding *)
let ( let+ ) p f = fmap f p

(** Аппликативный and-binding *)
let ( and+ ) p1 p2 = lift2 (fun a b -> (a, b)) p1 p2

(** Монадический let-binding *)
let ( let* ) p f = p >>= f

(** Монадический and-binding (аналогично and+) *)
